"""Check our terrain horizon against the LOLA long-term visibility maps (task T23).

For random points south of 85.5 S, computes the long-term visibility of the Sun and of the Earth with our pipeline
(SPICE + LOLA skyline) and compares it with the AVGVISIB maps (Mazarico et al. 2011, PGDA product 69).

Definition (from the maps' PDS labels, imbrium.mit.edu/EXTRAS/ILLUMINATION/IMG/*.LBL): the value is "the percentage of
timesteps where each pixel was sunlit (by any fraction of the ... disc)". So the like-for-like quantity is the share of
time with ANY part of the disk above the skyline. We also report the share with the disk CENTRE above the skyline and
our own metric, the time average of the VISIBLE DISK FRACTION; both are smaller by construction.

Run from the repo root:   .venv/Scripts/python.exe -m analysis.validate_avgvisib
Writes docs/validation/avgvisib.md. Needs the maps (python -m analysis.download_maps --all).

The comparison is not expected to be exact: the maps are 60 m pixel values from LDEM_85S_060M, ours are point values
from the newer 5 m / 80 m DEMs 2 m above the surface. A strong correlation and a small bias mean the skyline is right.
"""
from __future__ import annotations

from datetime import datetime, timezone

import numpy as np

from . import config, ephemeris as eph, metrics, terrain
from .metrics import Inputs

REPORT = config.REPO / "docs" / "validation" / "avgvisib.md"
DEFINITIONS = {"any_part": "any part of the disk visible (NASA's definition)",
               "centre": "disk centre above the skyline",
               "disk_fraction": "time-averaged visible disk fraction (our API metric)"}
N_POINTS = 150
START, END, STEP_S = "2020-01-01T00:00:00Z", "2038-08-01T00:00:00Z", 6 * 3600   # ~18.6 years, 6 h step
OBS_HEIGHT_M = 2.0


def run(n_points: int = N_POINTS, seed: int = 7) -> dict:
    rng = np.random.default_rng(seed)
    # Uniform over the cap 85.5 S .. pole (area-weighted), so the sample is not crowded at the pole.
    colat = np.degrees(np.arccos(1.0 - rng.uniform(0.0, 1.0, n_points) * (1.0 - np.cos(np.radians(4.5)))))
    lat, lon = -90.0 + colat, rng.uniform(-180.0, 180.0, n_points)
    ref_sun, ref_earth = terrain.lola_mean_visibility(lat, lon)
    bv = eph.body_vectors(START, END, STEP_S)
    ours = {f"{b}_{d}": np.empty(n_points) for b in ("sun", "earth") for d in DEFINITIONS}
    inp = Inputs(obs_height_m=OBS_HEIGHT_M)
    for i in range(n_points):                       # one site at a time keeps the memory small
        s = metrics.site_series(bv, lat[i], lon[i], inp)
        for b in ("sun", "earth"):
            f = s[f"{b}_visible_frac"][0]
            ours[f"{b}_any_part"][i] = (f > 0.0).mean()            # NASA's definition
            ours[f"{b}_centre"][i] = (f >= 0.5).mean()             # disk centre above the skyline
            ours[f"{b}_disk_fraction"][i] = f.mean()               # what our API averages
    return {"lat": lat, "lon": lon, "n_steps": len(bv), "ref": {"sun": ref_sun, "earth": ref_earth}, "ours": ours}


def stats(ref: np.ndarray, ours: np.ndarray) -> dict:
    ok = np.isfinite(ref) & np.isfinite(ours)
    d = ours[ok] - ref[ok]
    return {"n": int(ok.sum()), "r": float(np.corrcoef(ref[ok], ours[ok])[0, 1]), "bias": float(d.mean()),
            "mae": float(np.abs(d).mean()), "p90": float(np.percentile(np.abs(d), 90)),
            "both_zero": int(((ref[ok] < 0.005) & (ours[ok] < 0.005)).sum()), "ref_zero": int((ref[ok] < 0.005).sum())}


def report(res: dict) -> str:
    lines = [
        "# Validation: terrain horizon vs LOLA long-term visibility maps (T23)",
        "",
        f"Generated by `python -m analysis.validate_avgvisib` on {eph.format_utc(datetime.now(timezone.utc))}.",
        "",
        f"{len(res['lat'])} random points, uniform over the cap 85.5 S to the pole. Ours: {START[:10]} to {END[:10]} "
        f"({res['n_steps']} steps of {STEP_S // 3600} h), observer {OBS_HEIGHT_M} m above the terrain, skyline from the "
        "LOLA 5 m / 80 m DEMs out to 200 km. Reference: `AVGVISIB_85S_060M_201608` (Sun) and `_EARTH` "
        "(Mazarico et al. 2011, 60 m pixels, hourly steps over 18.6 years, computed on LDEM_85S_060M).",
        "",
        "**Definition.** The maps' PDS labels say the value is \"the percentage of timesteps where each pixel was sunlit "
        "(by any fraction of the ... disc)\". The like-for-like comparison is therefore the first row of each body.",
        "",
        "| Body | Our quantity | r | Mean difference (ours - map) | Mean abs difference | 90% within | Map 0: we agree |",
        "|---|---|---|---|---|---|---|",
    ]
    for body in ("sun", "earth"):
        for key, label in DEFINITIONS.items():
            st = stats(res["ref"][body], res["ours"][f"{body}_{key}"])
            lines.append(f"| {body.capitalize()} | {label} | {st['r']:.3f} | {st['bias']:+.3f} | {st['mae']:.3f} | "
                         f"{st['p90']:.3f} | {st['both_zero']} of {st['ref_zero']} |")
    lines += [
        "",
        "Values are fractions of time (0..1). The order any part >= centre >= disk fraction holds by construction; the gap "
        "is larger for the Earth (1.9 deg wide disk, lingering near the skyline) than for the Sun (0.5 deg). Remaining "
        "differences come from the pixel size (60 m map value vs our point value), the observer height and the DEMs.",
        "",
    ]
    return "\n".join(lines)


def main() -> None:
    text = report(run())
    REPORT.parent.mkdir(parents=True, exist_ok=True)
    REPORT.write_text(text, encoding="utf-8")
    print(text)


if __name__ == "__main__":
    main()
